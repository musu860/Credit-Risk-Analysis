-- MySQL schema for the cleaned loan dataset
CREATE DATABASE IF NOT EXISTS credit_risk_db CHARACTER SET utf8mb4;
USE credit_risk_db;

DROP TABLE IF EXISTS loan_data;
CREATE TABLE loan_data (
    id                          INT AUTO_INCREMENT PRIMARY KEY,
    SK_ID_CURR                  INT NOT NULL,
    NAME_CONTRACT_TYPE          VARCHAR(30),
    AMT_ANNUITY                 DECIMAL(14,2),
    AMT_APPLICATION             DECIMAL(14,2),
    AMT_CREDIT                  DECIMAL(14,2),
    AMT_DOWN_PAYMENT            DECIMAL(14,2),
    AMT_GOODS_PRICE             DECIMAL(14,2),
    WEEKDAY_APPR_PROCESS_START  VARCHAR(12),
    HOUR_APPR_PROCESS_START     TINYINT,
    FLAG_LAST_APPL_PER_CONTRACT CHAR(1),
    NFLAG_LAST_APPL_IN_DAY      TINYINT,
    RATE_DOWN_PAYMENT           DECIMAL(8,6),
    NAME_CASH_LOAN_PURPOSE      VARCHAR(60),
    NAME_CONTRACT_STATUS        VARCHAR(20),
    DAYS_DECISION               INT,
    NAME_PAYMENT_TYPE           VARCHAR(60),
    CODE_REJECT_REASON          VARCHAR(30),
    NAME_TYPE_SUITE             VARCHAR(30),
    NAME_CLIENT_TYPE            VARCHAR(20),
    NAME_GOODS_CATEGORY         VARCHAR(40),
    NAME_PORTFOLIO              VARCHAR(20),
    NAME_PRODUCT_TYPE           VARCHAR(20),
    CHANNEL_TYPE                VARCHAR(40),
    SELLERPLACE_AREA            INT,
    NAME_SELLER_INDUSTRY        VARCHAR(40),
    CNT_PAYMENT                 DECIMAL(6,1),
    NAME_YIELD_GROUP            VARCHAR(20),
    PRODUCT_COMBINATION         VARCHAR(60),
    DAYS_FIRST_DRAWING          DECIMAL(10,1),
    DAYS_FIRST_DUE              DECIMAL(10,1),
    DAYS_LAST_DUE_1ST_VERSION   DECIMAL(10,1),
    DAYS_LAST_DUE               DECIMAL(10,1),
    DAYS_TERMINATION            DECIMAL(10,1),
    NFLAG_INSURED_ON_APPROVAL   TINYINT,
    OUTLIER_AMT_ANNUITY         TINYINT,
    OUTLIER_AMT_APPLICATION     TINYINT,
    OUTLIER_AMT_CREDIT          TINYINT,
    OUTLIER_AMT_GOODS_PRICE     TINYINT,
    YEARS_SINCE_DECISION        DECIMAL(5,1),
    DECISION_YEAR_BUCKET        VARCHAR(10),
    CREDIT_BAND                 VARCHAR(25),
    IS_APPROVED                 TINYINT,
    IS_REFUSED                  TINYINT,
    CREDIT_TO_APPLICATION_RATIO DECIMAL(10,3),
    INDEX idx_status (NAME_CONTRACT_STATUS),
    INDEX idx_contract (NAME_CONTRACT_TYPE),
    INDEX idx_client (NAME_CLIENT_TYPE),
    INDEX idx_customer (SK_ID_CURR)
);
